problems = []
def tr_rect(tid):
    x0, x1, z0, z1, _ = TB[tid]
    return [(x0, z0), (x1, z0), (x1, z1), (x0, z1)]
def in_terrace(tid, x, z, tol=0.01):
    x0, x1, z0, z1, _ = TB[tid]
    return x0 - tol <= x <= x1 + tol and z0 - tol <= z <= z1 + tol
def terr_at(x, z):
    hits = [t for t in TB if in_terrace(t, x, z, tol=-0.01)]
    return hits

