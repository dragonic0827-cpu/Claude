def sat_sep(A, B):
    '''signed separation of convex polygons (>0 gap, <0 penetration depth)'''
    best = -1e9
    for poly in (A, B):
        n = len(poly)
        for i in range(n):
            x1, z1 = poly[i]; x2, z2 = poly[(i + 1) % n]
            nx, nz = -(z2 - z1), (x2 - x1); L = math.hypot(nx, nz); nx /= L; nz /= L
            pa = [q[0] * nx + q[1] * nz for q in A]; pb = [q[0] * nx + q[1] * nz for q in B]
            best = max(best, min(pb) - max(pa), min(pa) - max(pb))
    return best
