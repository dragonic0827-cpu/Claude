def seg_x(p1, p2, p3, p4):
    (x1, z1), (x2, z2), (x3, z3), (x4, z4) = p1, p2, p3, p4
    den = (x2 - x1) * (z4 - z3) - (z2 - z1) * (x4 - x3)
    if abs(den) < 1e-12: return None
    t = ((x3 - x1) * (z4 - z3) - (z3 - z1) * (x4 - x3)) / den
    u = ((x3 - x1) * (z2 - z1) - (z3 - z1) * (x2 - x1)) / den
    if 0 <= t <= 1 and 0 <= u <= 1: return (x1 + t * (x2 - x1), z1 + t * (z2 - z1))
    return None
def poly_crossings(pa, pb, closed_b):
    eb = list(zip(pb, pb[1:])) + ([(pb[-1], pb[0])] if closed_b else [])
