# stairs
spolys = {}
for s in stairs:
    r = s['rotationDeg']; a = (math.sin(math.radians(r)), -math.cos(math.radians(r)))
    top = (s['cx'] + a[0] * (s['run'] / 2 + 0.2), s['cz'] + a[1] * (s['run'] / 2 + 0.2))
    bot = (s['cx'] - a[0] * (s['run'] / 2 + 0.2), s['cz'] - a[1] * (s['run'] / 2 + 0.2))
    if not in_terrace(s['upperTerraceId'], *top): problems.append(f'STAIR {s["id"]} top not in upper terrace: {top}')
    if not in_terrace(s['lowerTerraceId'], *bot): problems.append(f'STAIR {s["id"]} bottom not in lower terrace: {bot}')
    # stair footprint: local width along x', run along ascent
    poly = rect_corners(s['cx'], s['cz'], s['width'], s['run'], r)
