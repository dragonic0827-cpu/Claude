buildings = []
def B(id, nameKo, nameHanja, kind, cx, cz, rot, terrace, front, side, pw, pd, ph, H, roof, rank, desc, conf,
      renamedTo=None, stories=1, bracket='jusimpo', tile='roofTile', extra=None):
    t = TB[terrace]
    b = dict(id=id, nameKo=nameKo, nameHanja=nameHanja)
    if renamedTo: b['renamedTo'] = renamedTo
    fw, sw = sum(front), sum(side)
    b.update(kind=kind, cx=R2(cx), cz=R2(cz), rotationDeg=rot, groundY=t[4], terraceId=terrace,
             baysFront=len(front), baysSide=len(side),
             bayWidth=R2(sorted(front)[len(front) // 2] if len(front) > 2 else front[0]),
             bayDepth=R2(sorted(side)[len(side) // 2] if len(side) > 2 else side[0]))
    if len(front) % 2 == 1 and front[len(front) // 2] != b['bayWidth']:
        b['centerBayWidth'] = front[len(front) // 2]
    b.update(bayWidthsFront=front, bayWidthsSide=side, columnSpanW=R2(fw), columnSpanD=R2(sw),
             platformW=pw, platformD=pd, platformHeight=ph, columnHeight=H, stories=stories,
             roof=roof, roofTileColor=tile, bracket=bracket, rank=rank, descriptionKo=desc, confidence=conf)
    if extra: b.update(extra)
    split_conf(b)
    assert pw >= fw and pd >= sw, (id, pw, fw, pd, sw)
    buildings.append(b)
    return b

