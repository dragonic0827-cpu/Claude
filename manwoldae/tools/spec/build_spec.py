def dist_seg(px, pz, a, b):
    ax, az = a; bx, bz = b; dx, dz = bx - ax, bz - az
    t = max(0.0, min(1.0, ((px - ax) * dx + (pz - az) * dz) / (dx * dx + dz * dz)))
    return math.hypot(px - ax - t * dx, pz - az - t * dz)
def pip(px, pz, poly):
    inside = False; n = len(poly)
    for i in range(n):
        x1, z1 = poly[i]; x2, z2 = poly[(i + 1) % n]
        if (z1 > pz) != (z2 > pz):
            if px < x1 + (pz - z1) * (x2 - x1) / (z2 - z1): inside = not inside
    return inside
def zone_w(x, z):
    if pip(x, z, zone_poly): return 1.0
    d = min(dist_seg(x, z, zone_poly[i], zone_poly[(i + 1) % len(zone_poly)]) for i in range(len(zone_poly)))
    return 1.0 if d < 50 else max(0.0, 1 - (d - 50) / 90.0)
