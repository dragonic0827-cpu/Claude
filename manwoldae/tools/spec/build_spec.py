def sample_grid(g, x, z):
    fx = (x - g['x0']) / g['step']; fz = (z - g['z0']) / g['step']
    i = int(math.floor(fx)); j = int(math.floor(fz))
    if not (0 <= i < g['nx'] - 1 and 0 <= j < g['nz'] - 1): return None
    tx, tz = fx - i, fz - j; v = g['values']; nx = g['nx']
    return (v[j * nx + i] * (1 - tx) * (1 - tz) + v[j * nx + i + 1] * tx * (1 - tz) + v[(j + 1) * nx + i] * (1 - tx) * tz + v[(j + 1) * nx + i + 1] * tx * tz)
