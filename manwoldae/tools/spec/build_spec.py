def rotvec(u, v, rdeg):
    """rotate local (u east, v south) clockwise (compass sense) by rdeg"""
    r = math.radians(rdeg)
    return (u * math.cos(r) - v * math.sin(r), u * math.sin(r) + v * math.cos(r))

